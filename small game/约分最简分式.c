/*约分最简分式
分数可以表示为分子/分母的形式，编写一个程序，要求用户输入一个分数，然后将其约分为最简分式，最简分式是指分子和分母不具有可以约分的成分
如6/12可以被约分成1/2，当分子大于分母时，不需要表达整数又分数的形式，即11/8还是11/8，而当分子分母相等时，仍然表达为1/1的分数形式
输入格式：
输入一行中给出一个分数，分子和分母中间以斜杠/分隔，如12/34可以表示为34分之12。分子和分母都是正整数(不包含0，如果不清楚正整数定义的话
) 提示：在scanf的格式字符串中加入/，让scanf处理这个斜杠
输出格式：
在一行中输出这个分数对应的最简分式，格式与输入的相同，即采用分子/分母的形式表示分数如5/6表示6分之五
输入样例：
60/120
输出样例：
1/2
*/
#include <stdio.h>
int main(void)
{
	int dividend, divisor;
	scanf("%d/%d", &dividend, &divisor);
	
	int a = dividend;
	int b = divisor;
	int t;
	while(b>0){
		t = a % b;
		a = b;
		b = t;
	}
	printf("%d/%d\n", dividend/a, divisor/a);
	
	return 0;
}
