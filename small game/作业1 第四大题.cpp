/*
程序名称：温度换算
设计思路：1.明确换算公式：华氏温度 f = 9.0/5.0 * c + 32；
 *   2. 温度可能带有小数（如 36.5 摄氏度），因此变量 c、f 均定义为
 *      double 双精度浮点型；
 *   3. 公式中必须写成 9.0 和 5.0 而不是 9 和 5：
 *      若写 9/5，两个整数相除结果为整数 1，会丢失精度导致计算错误；
 *      写成 9.0/5.0 则执行浮点除法，结果为 1.8，保证换算正确；
 *   4. 输入时 scanf 使用 %lf 读取 double 类型；
 *   5. 输出时用 %.2f 格式控制，使结果保留 2 位小数。*/



#include <stdio.h>

int main(void)
{
	// 第一步：输入摄氏温度 //
	double c,f;                      // 把c,f定义为doublel类型 //
	printf("请输入摄氏温度");        // 输出文本 //
	scanf("%lf", &c);                // 输入摄氏温度 //
	
	// 第二步：按公式进行换算 //
	f = 9.0/5.0*c+32;                // 公式描述 //
	
	// 第三步：输出华氏温度同时保留两位小数 //
	printf("华氏温度为：%2.f\n",f);  // 输出文本 //
	
	return 0;
}

