// 倒序分解整数
#include <stdio.h>

int main(void)                                       // 但是如果输入的是末尾只有0的数字 那么输出就有错误了
													 // 这边有个计算过程 	(怎么取最高位)
													 // x = 1234
													 // 1234 / 1000 -> 1
													 // 1234 % 1000 -> 234
													 // 1000 / 10   -> 100
													 // 234  / 100  -> 2
													 // 234  % 100  -> 34
													 // 100  / 10   -> 10
													 // 34   / 10   -> 3
													 // 34   % 10   -> 4
													 // 10   / 10   -> 1
													 // 4    / 1    -> 4
													 // 4    % 1    -> 0
													 // 1    / 10   -> 0
{
	int x;
	//scanf("%d", x);
	x = 700;                 // debug
	int t = 0;
	
	// 先做一遍逆序
	do {
		int d = x%10;
		t = t*10+d;
		x /= 10;
		
	}while(x > 0);
	printf("x=%d,t=%d\n", x, t);
	x = t;
	
	// 再做一遍逆序就又回来了
	do {
		int digit = x%10;
		printf("%d", digit);
		if (x > 9){
			printf(" ");
		}
		x /= 10;
	}while(x>0);
	printf("\n");
	return 0;
}

