/*条件运算
count=(count>20)?count-10:count+10;
条件?条件满足时的值:条件不满足时的值
条件运算符的优先级高于赋值运算符，但是低于其他运算符
条件运算符是自右向左结合的
*/

/*逗号运算符
逗号用来连接两个表达式，并以其右边的表达式的值作为他的结果。逗号的优先级是所有的运算符中最低的
所以他两边的表达式会先进行计算；逗号的组合方式是自左向右，所以左边的表达式会先计算，而右边的表达式的值
就留下来作为逗号的结果
*/
#include <stdio.h>
int main(void)
{
	int i;
	i = (3+4,5+4);
	
	printf("%d", i);
	
	return 0;
}
