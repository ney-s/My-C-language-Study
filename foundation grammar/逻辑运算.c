/*逻辑运算
! 逻辑非, !a,结果 如果a是true那么就是false
&& 逻辑与,a&&b,如果a和b都是true，结果就是true，否则就是false
|| 逻辑或，a||b,如果a和b有一个是true那么结果就是true，两个都是false那么都是false
优先级 !>&&>||*/

/*运算符优先级
优先级	运算符				综合性
1.		()					从左到右
2.		! + - ++ -- 		从右到左(单目的+和-)
3. 		* /%        		从左到右
4.		+ -					从左到右
5.		< <= > >=			从左到右
6.		== !=				从左到右
7.		&&					从左到右
8.		||					从左到右
9.		= += -= *= /= %=	从右到左
*/

// 如果&&左边的条件已经不成立，那么就短路不会执行右边的条件
#include <stdio.h>
int main(void)
{
	int a = -1;
	if(a>0 && a++>1){
		printf("OK\n");
	}
	printf("a=%d", a);
	
	return 0;
	
} 
